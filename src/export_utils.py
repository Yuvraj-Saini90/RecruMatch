"""Export utilities for generating CSV reports and recruiter audit summaries."""

import io
from typing import List, Dict, Any
import pandas as pd


def generate_candidate_dataframe(ranked_candidates: List[Dict[str, Any]]) -> pd.DataFrame:
    """Convert ranked candidate assessments to a structured pandas DataFrame."""
    rows = []
    for c in ranked_candidates:
        prof = c.get("candidate_profile", {})
        req = c.get("required_skills_result", {})
        pref = c.get("preferred_skills_result", {})
        exp = c.get("experience_result", {})
        edu = c.get("education_result", {})
        sim = c.get("similarity_result", {})

        rows.append({
            "Rank": c.get("rank", 0),
            "Candidate Name": c.get("candidate_name", "Not detected"),
            "Overall Score (%)": c.get("overall_score", 0.0),
            "Match Category": c.get("category", {}).get("label", ""),
            "Required Skills Score (%)": req.get("score", 0.0),
            "Preferred Skills Score (%)": pref.get("score", 0.0),
            "Experience Score (%)": exp.get("score", 0.0),
            "Education Score (%)": edu.get("score", 0.0),
            "Resume-JD Similarity (%)": sim.get("score", 0.0),
            "Matched Required Skills": ", ".join(req.get("matched", [])),
            "Missing Required Skills": ", ".join(req.get("missing", [])),
            "Candidate Experience": exp.get("candidate_years", 0.0),
            "Candidate Degree": edu.get("candidate_degree", "Not detected"),
            "Email": prof.get("email", "Not detected"),
            "Phone": prof.get("phone", "Not detected"),
            "File Name": c.get("filename", "")
        })

    return pd.DataFrame(rows)


def export_results_to_csv(ranked_candidates: List[Dict[str, Any]]) -> str:
    """Generate CSV string from ranked candidates."""
    df = generate_candidate_dataframe(ranked_candidates)
    return df.to_csv(index=False)


def generate_recruiter_markdown_report(
    ranked_candidates: List[Dict[str, Any]],
    jd_analysis: Dict[str, Any]
) -> str:
    """Generate a clean text/markdown screening audit report."""
    lines = [
        "# Smart Resume Screening & Candidate Ranking Audit Report",
        f"**Date Generated:** October 2026",
        f"**Department:** Computer Science & Engineering | GNIOT Greater Noida",
        f"**Total Resumes Screened:** {len(ranked_candidates)}",
        "",
        "## Job Requirements Summary",
        f"- **Required Skills:** {', '.join(jd_analysis.get('required_skills', [])) or 'None specified'}",
        f"- **Preferred Skills:** {', '.join(jd_analysis.get('preferred_skills', [])) or 'None specified'}",
        f"- **Target Experience:** {jd_analysis.get('experience_text', 'Not specified')}",
        f"- **Target Education:** {jd_analysis.get('education_text', 'Not specified')}",
        "",
        "## Candidate Ranking Leaderboard",
        "| Rank | Candidate | Score | Tier | Required Skills | Missing Skills | Experience |",
        "| :--- | :--- | :---: | :--- | :--- | :--- | :--- |"
    ]

    for c in ranked_candidates:
        req = c.get("required_skills_result", {})
        exp = c.get("experience_result", {})
        matched_str = f"{req.get('matched_count', 0)}/{req.get('total_count', 0)}"
        missing_str = ", ".join(req.get("missing", [])[:3]) or "None"
        exp_str = f"{exp.get('candidate_years', 0.0):g} yrs"

        lines.append(
            f"| #{c.get('rank', 0)} | {c.get('candidate_name', 'Not detected')} | "
            f"**{c.get('overall_score', 0.0):.1f}%** | {c.get('category', {}).get('label', '')} | "
            f"{matched_str} | {missing_str} | {exp_str} |"
        )

    lines.extend([
        "",
        "---",
        "**Human-in-the-Loop Advisory:** This screening report is generated by an automated assistive tool.",
        "Final candidate evaluation, interview progression, and hiring selections strictly remain with the recruiter."
    ])

    return "\n".join(lines)
